"""Render ``docs/RESULTS.md`` from the claims ledger ``results/claims.csv``.

The ledger is written by :mod:`metagross.eval.claims` (never by hand). This module only formats it:
one section per honesty label (Tested, Simulated, Estimated, Proposed, Literature, then any other
label), one table row per claim, and a relative link from the Markdown file to the results file each
claim comes from. No numbers are computed here, and the output carries no timestamp, so the same
ledger always gives a byte-identical page (the ledger's sha256 is printed for provenance).

Usage::

    python -m metagross.eval.claims        # regenerate results/claims.csv from results/*.json
    python -m metagross.eval.results_md    # then regenerate docs/RESULTS.md
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import logging
import os
from pathlib import Path
from typing import Iterable

from metagross.eval.claims import LABELS

LOG = logging.getLogger(__name__)
REPO = Path(__file__).resolve().parents[2]
CLAIMS_CSV = REPO / "results" / "claims.csv"
RESULTS_MD = REPO / "docs" / "RESULTS.md"
COLUMNS = ("id", "value", "unit", "label", "source", "note")
OTHER_LABEL = "Other"  # section for rows whose label is not one of claims.LABELS

#: One-line meaning of each honesty label, printed under its heading.
LABEL_MEANING: dict[str, str] = {
    "Tested": "Measured by us on real data (real images, real hardware timing).",
    "Simulated": "Measured by us inside the simulator (rendered or synthetic sensor data).",
    "Estimated": "Computed from an analytic model with stated assumptions; not a measurement.",
    "Proposed": "A design value or plan; not yet built or measured.",
    "Literature": "Taken from a publication or public benchmark; not our measurement.",
    OTHER_LABEL: "Rows with a non-standard label; fix the label in the source results file.",
}


def load_claims(path: Path = CLAIMS_CSV) -> list[dict[str, str]]:
    """Read the ledger; every row gets all :data:`COLUMNS` (missing -> empty string)."""
    with Path(path).open(newline="", encoding="utf-8") as fh:
        return [{c: (row.get(c) or "").strip() for c in COLUMNS} for row in csv.DictReader(fh)]


def _cell(text: str) -> str:
    """Make a string safe inside a Markdown table cell."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def source_link(source: str, md_dir: Path, repo: Path = REPO) -> str:
    """``results/x.json#a.b`` -> ``[results/x.json#a.b](../results/x.json)`` relative to ``md_dir``.

    The JSON path after ``#`` stays in the link text (JSON has no anchors). Sources that are not
    repository paths (URLs, free text) are returned as escaped text, URLs as links."""
    if not source:
        return ""
    if source.startswith(("http://", "https://")):
        return f"[{_cell(source)}]({source})"
    file_part = source.split("#", 1)[0]
    target = repo / file_part
    if not file_part or not target.exists():
        return _cell(source)
    try:
        rel = Path(os.path.relpath(target, md_dir)).as_posix()
    except ValueError:  # Markdown written on another drive (Windows): no relative path exists
        return _cell(source)
    return f"[{_cell(source)}]({rel.replace(' ', '%20')})"


def group_by_label(rows: Iterable[dict[str, str]]) -> dict[str, list[dict[str, str]]]:
    """Label -> rows sorted by id; labels in :data:`claims.LABELS` order, unknown labels last."""
    groups: dict[str, list[dict[str, str]]] = {}
    for r in rows:
        key = r["label"] if r["label"] in LABELS else OTHER_LABEL
        groups.setdefault(key, []).append(r)
    order = [lab for lab in (*LABELS, OTHER_LABEL) if lab in groups]
    return {lab: sorted(groups[lab], key=lambda r: r["id"].lower()) for lab in order}


def render(rows: list[dict[str, str]], md_dir: Path = RESULTS_MD.parent, ledger_name: str = "results/claims.csv",
           ledger_sha256: str = "") -> str:
    """The complete RESULTS.md text for ``rows``."""
    groups = group_by_label(rows)
    out = [
        "# METAGROSS results (claims ledger)",
        "",
        f"Generated by `metagross/eval/results_md.py` from `{ledger_name}`. Do not edit by hand: change the",
        "results file, run `python -m metagross.eval.claims`, then `python -m metagross.eval.results_md`.",
        "",
        "Every number shown on a slide or in the video must appear here with its label and source.",
        "Other documents may cite a results file directly; they name the file next to the number.",
        "",
    ]
    if ledger_sha256:
        out += [f"Ledger sha256: `{ledger_sha256}`", ""]
    out += ["| label | claims |", "|---|---:|"]
    out += [f"| [{lab}](#{lab.lower()}) | {len(g)} |" for lab, g in groups.items()]
    out += [f"| total | {sum(len(g) for g in groups.values())} |", ""]
    for lab, g in groups.items():
        out += [f"## {lab}", "", LABEL_MEANING.get(lab, ""), "", "| id | value | unit | note | source |",
                "|---|---:|---|---|---|"]
        for r in g:
            out.append(f"| {_cell(r['id'])} | {_cell(r['value'])} | {_cell(r['unit'])} | {_cell(r['note'])} | "
                       f"{source_link(r['source'], md_dir)} |")
        out.append("")
    if not groups:
        out += ["The ledger is empty.", ""]
    return "\n".join(out)


def write_results_md(claims_csv: Path = CLAIMS_CSV, out: Path = RESULTS_MD) -> Path:
    """Render ``claims_csv`` into ``out`` (UTF-8, LF line endings); returns ``out``."""
    claims_csv, out = Path(claims_csv), Path(out)
    digest = hashlib.sha256(claims_csv.read_bytes()).hexdigest()
    try:
        name = claims_csv.resolve().relative_to(REPO).as_posix()
    except ValueError:
        name = claims_csv.name
    text = render(load_claims(claims_csv), out.parent, name, digest)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    LOG.info("wrote %s from %s", out, claims_csv)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Render docs/RESULTS.md from results/claims.csv")
    ap.add_argument("--claims", type=Path, default=CLAIMS_CSV)
    ap.add_argument("--out", type=Path, default=RESULTS_MD)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    write_results_md(a.claims, a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
